"""
Day 1: Variables and Data Types

Learning Objectives:
- Understand how to create and use variables
- Learn about different data types (int, float, str, bool)
- Practice variable naming conventions
- Understand type conversion

Expected Output:
Hello, Alice!
Age: 25
Height: 5.8
Is student: True
"""

# Variables and Assignment
name = "Alice"
age = 25
height = 5.8
is_student = True

# Printing variables
print(f"Hello, {name}!")
print(f"Age: {age}")
print(f"Height: {height}")
print(f"Is student: {is_student}")

# Type checking
print(f"\nType of name: {type(name)}")
print(f"Type of age: {type(age)}")
print(f"Type of height: {type(height)}")
print(f"Type of is_student: {type(is_student)}")

